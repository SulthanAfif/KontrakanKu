create function public.current_app_role()
returns public.app_role
language sql
stable
security definer
set search_path = ''
as $$
  select role from public.profiles where id = (select auth.uid())
$$;

alter table public.profiles enable row level security;
alter table public.rooms enable row level security;
alter table public.tenants enable row level security;
alter table public.contracts enable row level security;
alter table public.payments enable row level security;
alter table public.booking_requests enable row level security;
alter table public.settings enable row level security;

create policy "Profiles are visible to their owner and admins" on public.profiles
  for select to authenticated using (id = (select auth.uid()) or public.current_app_role() = 'admin');
-- Role updates are intentionally restricted to trusted project administrators.

create policy "Available room catalog is public" on public.rooms
  for select to anon, authenticated using (status in ('kosong', 'terisi'));
create policy "Admins manage rooms" on public.rooms
  for all to authenticated using (public.current_app_role() in ('admin', 'pemilik'))
  with check (public.current_app_role() in ('admin', 'pemilik'));
create policy "Tenants can view their contracted room" on public.rooms
  for select to authenticated using (exists (
    select 1 from public.contracts
    join public.tenants on tenants.id = contracts.tenant_id
    where contracts.room_id = rooms.id
      and tenants.user_id = (select auth.uid())
      and contracts.status = 'aktif'
  ));

create policy "Tenants see their own record" on public.tenants
  for select to authenticated using (user_id = (select auth.uid()) or public.current_app_role() in ('admin', 'pemilik'));
create policy "Admins manage tenants" on public.tenants
  for all to authenticated using (public.current_app_role() in ('admin', 'pemilik'))
  with check (public.current_app_role() in ('admin', 'pemilik'));

create policy "Tenants see their contracts" on public.contracts
  for select to authenticated using (
    public.current_app_role() in ('admin', 'pemilik') or exists (
      select 1 from public.tenants where tenants.id = contracts.tenant_id and tenants.user_id = (select auth.uid())
    )
  );
create policy "Admins manage contracts" on public.contracts
  for all to authenticated using (public.current_app_role() in ('admin', 'pemilik'))
  with check (public.current_app_role() in ('admin', 'pemilik'));

create policy "Tenants see their payments" on public.payments
  for select to authenticated using (
    public.current_app_role() in ('admin', 'pemilik') or exists (
      select 1 from public.contracts join public.tenants on tenants.id = contracts.tenant_id
      where contracts.id = payments.contract_id and tenants.user_id = (select auth.uid())
    )
  );
create policy "Admins manage payments" on public.payments
  for all to authenticated using (public.current_app_role() in ('admin', 'pemilik'))
  with check (public.current_app_role() in ('admin', 'pemilik'));

create policy "Customers read and create their bookings" on public.booking_requests
  for select to authenticated using (user_id = (select auth.uid()) or public.current_app_role() in ('admin', 'pemilik'));
create policy "Customers create their own bookings" on public.booking_requests
  for insert to authenticated with check (
    user_id = (select auth.uid())
    and exists (select 1 from public.rooms where rooms.id = room_id and rooms.status = 'kosong')
  );
create policy "Admins manage booking status" on public.booking_requests
  for update to authenticated using (public.current_app_role() in ('admin', 'pemilik'))
  with check (public.current_app_role() in ('admin', 'pemilik'));

create policy "Contact settings are public" on public.settings
  for select to anon, authenticated using (true);
create policy "Admins manage settings" on public.settings
  for all to authenticated using (public.current_app_role() in ('admin', 'pemilik'))
  with check (public.current_app_role() in ('admin', 'pemilik'));
