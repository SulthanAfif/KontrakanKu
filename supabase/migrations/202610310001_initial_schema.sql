-- Initial Supabase schema for the Kontrakanku rental platform.
-- Run with: supabase db push

create type public.app_role as enum ('admin', 'pemilik', 'penyewa');
create type public.room_status as enum ('kosong', 'terisi', 'maintenance');
create type public.tenant_status as enum ('aktif', 'nonaktif');
create type public.contract_status as enum ('aktif', 'berakhir', 'dibatalkan');
create type public.payment_status as enum ('belum_bayar', 'lunas', 'terlambat');
create type public.booking_status as enum ('pending', 'diproses', 'diterima', 'ditolak');

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null,
  role public.app_role not null default 'penyewa',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name', new.email));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

create table public.rooms (
  id bigint generated by default as identity primary key,
  kode_kamar text not null unique,
  kode_rumah text not null unique,
  deskripsi text,
  harga_sewa numeric(12, 2) not null check (harga_sewa >= 0),
  status public.room_status not null default 'kosong',
  lantai integer not null default 1,
  kapasitas integer not null default 1 check (kapasitas > 0),
  fasilitas jsonb not null default '[]'::jsonb,
  foto jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.tenants (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles (id) on delete set null,
  nama_lengkap text not null,
  nik text not null unique,
  no_hp text not null,
  email text,
  alamat_asal text,
  kontak_darurat text,
  no_hp_darurat text,
  foto_ktp text,
  status public.tenant_status not null default 'aktif',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.contracts (
  id bigint generated by default as identity primary key,
  nomor_kontrak text not null unique,
  room_id bigint not null references public.rooms (id) on delete cascade,
  tenant_id bigint not null references public.tenants (id) on delete cascade,
  tanggal_mulai date not null,
  tanggal_berakhir date not null,
  harga_sewa numeric(12, 2) not null check (harga_sewa >= 0),
  deposit numeric(12, 2) not null default 0 check (deposit >= 0),
  status public.contract_status not null default 'aktif',
  catatan text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint contract_dates_valid check (tanggal_berakhir >= tanggal_mulai)
);

create table public.payments (
  id bigint generated by default as identity primary key,
  contract_id bigint not null references public.contracts (id) on delete cascade,
  periode text not null,
  jumlah numeric(12, 2) not null check (jumlah >= 0),
  tanggal_jatuh_tempo date not null,
  tanggal_bayar date,
  status public.payment_status not null default 'belum_bayar',
  metode_bayar text,
  bukti_transfer text,
  catatan text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (contract_id, periode)
);

create table public.booking_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  room_id bigint not null references public.rooms (id) on delete cascade,
  nama_lengkap text not null,
  nik text,
  no_hp text not null,
  email text,
  alamat_asal text,
  kontak_darurat text,
  no_hp_darurat text,
  tanggal_mulai_diinginkan date,
  pesan text,
  status public.booking_status not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.settings (
  key text primary key,
  value text,
  updated_at timestamptz not null default now()
);

